// sync-contract/scripts/generate-crop-names.ts
//
// spec: plr-d10-redesign-real-integration-2026-10-25 — lane L8b-1 (Review Focus 3: "one shared crop <-> schedule rule,
// not two"). The server must read a crop season's crop name exactly as the phone's schedule library does: through the
// founder's crop master (any English or Marathi name, canonical or alternate). The master lives in the phone
// (src/clients/mobile-web/src/domain/crops/cropMasterData.ts, generated from the founder's sheet); this script writes the
// NAMES the rule needs — id, English, Marathi, alternates, base crop — to schemas/crop-names.json, which the server embeds
// (ShramSafal.Application, ScheduleLibrary). Nothing else of the master is copied.
//
// Re-run whenever cropMasterData.ts is regenerated:
//     cd sync-contract && npx tsx scripts/generate-crop-names.ts
// The phone's vitest `cropNamesForServer.parity.test.ts` fails while the two disagree.
import { writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { CROP_MASTER_ROWS, CROP_MASTER_SOURCE } from '../../src/clients/mobile-web/src/domain/crops/cropMasterData';

const rows = CROP_MASTER_ROWS.map(r => ({ id: r.id, en: r.en, mr: r.mr, altEn: [...r.altEn], altMr: [...r.altMr], base: r.base }));

const lines = [
    '{',
    `  "_comment": ${JSON.stringify('AUTO-GENERATED by sync-contract/scripts/generate-crop-names.ts from the phone crop master (cropMasterData.ts). Do not edit by hand. The server reads crop names through these rows exactly as the phone does (lane L8b-1).')},`,
    `  "source": ${JSON.stringify(CROP_MASTER_SOURCE)},`,
    '  "rows": [',
    ...rows.map((r, i) => `    ${JSON.stringify(r)}${i === rows.length - 1 ? '' : ','}`),
    '  ]',
    '}',
    '',
];

const outPath = fileURLToPath(new URL('../schemas/crop-names.json', import.meta.url));
await writeFile(outPath, lines.join('\n'), 'utf8');
console.log(`Wrote ${rows.length} crop rows to ${outPath}`);
